// Archive layout below storage.root. Hidden photos get their own folder, which
// the agent hides on disk (platform.MarkHidden). It cannot be a dot-folder:
// kei strips leading dots from every path component (sanitize_path_component).
const (
	PhotosDir = "Photos"
	HiddenDir = "Hidden"
	// dateFolders renders the capture month; every pass uses it, so an asset
	// can only ever have one place in the archive.
	dateFolders = "%Y/%m"
	reportFile  = "sync-report.json"
)

// hiddenSmartFolder is Apple's smart folder for hidden assets, which iCloud's
// library-wide "All Photos" view (kei's unfiled pass) leaves out.
const hiddenSmartFolder = "Hidden"

const configHeader = "# Generated by homecloud from its config.toml every time the agent starts.\n" +
	"# Edits here are overwritten; change homecloud's configuration instead.\n" +
	"# Choices and kei documentation references: homecloud docs/design.md §10.\n\n"

// keiConfig is the subset of kei v0.24 configuration homecloud sets
// (kei example.config.toml). Everything else stays at kei's defaults.
type keiConfig struct {
	Auth struct {
		Username string `toml:"username"`
	} `toml:"auth"`
	Download struct {
		Directory                   string `toml:"directory"`
		FolderStructure             string `toml:"folder_structure"`
		FolderStructureAlbums       string `toml:"folder_structure_albums"`
		FolderStructureSmartFolders string `toml:"folder_structure_smart_folders"`
	} `toml:"download"`
	Filters struct {
		Libraries    []string `toml:"libraries"`
		Albums       []string `toml:"albums"`
		SmartFolders []string `toml:"smart_folders"`
		Unfiled      bool     `toml:"unfiled"`
		Media        []string `toml:"media"`
	} `toml:"filters"`
	Photos struct {
		Resolution             string `toml:"resolution"`
		LiveResolution         string `toml:"live_resolution"`
		LivePhotoMode          string `toml:"live_photo_mode"`
		Edited                 bool   `toml:"edited"`
		Alternative            bool   `toml:"alternative"`
		FileMatchPolicy        string `toml:"file_match_policy"`
		KeepUnicodeInFilenames bool   `toml:"keep_unicode_in_filenames"`
	} `toml:"photos"`
	Metadata struct {
		XMPSidecar bool `toml:"xmp_sidecar"`
	} `toml:"metadata"`
	Report struct {
		JSON string `toml:"json"`
	} `toml:"report"`
	Server struct {
		Bind string `toml:"bind"`
	} `toml:"server"`
}

// RenderConfig returns kei's configuration for cfg: the whole primary library
// in original quality with every rendition (edits, Live Photo videos, RAW
// alternatives), one date-folder tree, XMP sidecars, and the Hidden smart
// folder when icloud.include_hidden is set.
func RenderConfig(cfg *config.Config) ([]byte, error) {
	var k keiConfig
	k.Auth.Username = cfg.ICloud.AppleID
	k.Download.Directory = filepath.Join(cfg.Storage.Root, PhotosDir)
	k.Download.FolderStructure = dateFolders
	k.Download.FolderStructureAlbums = dateFolders
	k.Download.FolderStructureSmartFolders = HiddenDir + "/" + dateFolders
	k.Filters.Libraries = []string{"primary"}
	k.Filters.Albums = []string{"none"}
	k.Filters.SmartFolders = []string{"none"}
	if *cfg.ICloud.IncludeHidden {
		k.Filters.SmartFolders = []string{hiddenSmartFolder}
	}
	k.Filters.Unfiled = true
	k.Filters.Media = []string{"photos", "videos", "live-photos"}
	k.Photos.Resolution = "original"
	k.Photos.LiveResolution = "original"
	k.Photos.LivePhotoMode = "both"
	k.Photos.Edited = true
	k.Photos.Alternative = true
	k.Photos.FileMatchPolicy = "name-id7"
	k.Photos.KeepUnicodeInFilenames = true
	k.Metadata.XMPSidecar = true
	k.Report.JSON = filepath.Join(filepath.Dir(cfg.Kei.Config), reportFile)
	k.Server.Bind = "127.0.0.1"

	body, err := toml.Marshal(k)
	if err != nil {
		return nil, fmt.Errorf("render kei config: %w", err)
	}
	return append([]byte(configHeader), body...), nil
}

// WriteConfig writes kei's configuration to kei.config when it differs from
// what is there, and reports whether it changed. The file names the Apple
// Account, so it is readable by the current user only.
func WriteConfig(cfg *config.Config) (bool, error) {
	want, err := RenderConfig(cfg)
	if err != nil {
		return false, err
	}
	have, err := os.ReadFile(cfg.Kei.Config)
	switch {
	case err == nil && bytes.Equal(have, want):
		return false, nil
	case err != nil && !errors.Is(err, fs.ErrNotExist):
		return false, fmt.Errorf("read kei config: %w", err)
	}
	if err := os.MkdirAll(filepath.Dir(cfg.Kei.Config), 0o700); err != nil {
		return false, fmt.Errorf("create kei config directory: %w", err)
	}
	if err := platform.WriteSecretFile(cfg.Kei.Config, want); err != nil {
		return false, fmt.Errorf("write kei config: %w", err)
	}
	return true, nil
}

// ConfigCurrent reports whether kei.config holds exactly what RenderConfig produces.
func ConfigCurrent(cfg *config.Config) error {
	want, err := RenderConfig(cfg)
	if err != nil {
		return err
	}
	have, err := os.ReadFile(cfg.Kei.Config)
	if err != nil {
		return fmt.Errorf("read kei config: %w", err)
	}
	if !bytes.Equal(have, want) {
		return fmt.Errorf("%s differs from homecloud's settings; the agent rewrites it when it starts", cfg.Kei.Config)
	}
	return nil
}

// HiddenPath is the folder holding photos hidden in iCloud under root.
func HiddenPath(root string) string {
	return filepath.Join(root, PhotosDir, HiddenDir)
}
