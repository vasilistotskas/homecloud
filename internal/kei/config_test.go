package kei

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/pelletier/go-toml/v2"

	"github.com/vasilistotskas/homecloud/internal/config"
)

func testConfig(t *testing.T, includeHidden bool) *config.Config {
	t.Helper()
	root := t.TempDir()
	return &config.Config{
		Storage: config.Storage{Root: root},
		ICloud:  config.ICloud{AppleID: "someone@example.com", IncludeHidden: &includeHidden},
		Kei:     config.Kei{Config: filepath.Join(root, "kei", "config.toml")},
	}
}

func TestRenderConfig(t *testing.T) {
	for _, hidden := range []bool{true, false} {
		cfg := testConfig(t, hidden)
		out, err := RenderConfig(cfg)
		if err != nil {
			t.Fatal(err)
		}
		if !strings.HasPrefix(string(out), "# Generated by homecloud") {
			t.Fatalf("missing header:\n%s", out)
		}
		var k keiConfig
		if err := toml.NewDecoder(strings.NewReader(string(out))).DisallowUnknownFields().Decode(&k); err != nil {
			t.Fatalf("rendered config does not round-trip: %v\n%s", err, out)
		}
		wantSmart := "none"
		if hidden {
			wantSmart = "Hidden"
		}
		if k.Auth.Username != "someone@example.com" || k.Download.Directory != filepath.Join(cfg.Storage.Root, "Photos") ||
			k.Download.FolderStructureAlbums != "%Y/%m" || k.Download.FolderStructureSmartFolders != "Hidden/%Y/%m" ||
			len(k.Filters.SmartFolders) != 1 || k.Filters.SmartFolders[0] != wantSmart || !k.Metadata.XMPSidecar {
			t.Fatalf("hidden=%v rendered %+v", hidden, k)
		}
	}
}

func TestWriteConfigOnlyWhenChanged(t *testing.T) {
	cfg := testConfig(t, true)
	if changed, err := WriteConfig(cfg); err != nil || !changed {
		t.Fatalf("first write = %v, %v", changed, err)
	}
	if err := ConfigCurrent(cfg); err != nil {
		t.Fatal(err)
	}
	if changed, err := WriteConfig(cfg); err != nil || changed {
		t.Fatalf("second write = %v, %v; want unchanged", changed, err)
	}
	if err := os.WriteFile(cfg.Kei.Config, []byte("edited"), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := ConfigCurrent(cfg); err == nil {
		t.Fatal("an edited config must be reported")
	}
	if changed, err := WriteConfig(cfg); err != nil || !changed {
		t.Fatalf("rewrite after edit = %v, %v", changed, err)
	}
}
